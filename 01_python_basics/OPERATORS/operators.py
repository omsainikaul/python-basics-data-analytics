a = 10
b = 3

# Arithematic Operators

print(a + b)
print(a - b)
print(a * b)
print(a ** b)
print(a / b)
print(a // b)
print(a % b)

# Comparison Operators

print(a == b)
print(a != b)
print(a > b)
print(a >= b)
print(a < b)
print(a <= b)

# Assignment Operators

a += 4
b += 4
print(a, b)

a -= 4
b -= 4
print(a, b)

a *= 4
b *= 4
print(a, b)

# Logical Operators

print(True and False)  # Both must be True
print(True and  True)
print(False and False)
print(True or False)  # At least one True
print(True or True)
print(False or False)
print(not(True)) # Reverses Result
print(not(False))